#[tokio::test]
#[ignore]
async fn test_message_serialization_integration() {
    let request = TestRequest {
        message: "Hello from integration test".to_string(),
    };
    
    let json = request.to_json();
    assert!(!json.is_empty());
    
    // Verify round-trip
    let deserialized: TestRequest = serde_json::from_str(&json).unwrap();
    assert_eq!(deserialized.message, "Hello from integration test");
}

#[test]
fn test_error_response_format() {
    let error = DefaultResponseErrorSchema {
        code: 500,
        message: "Test error message".to_string(),
    };
    
    let json = error.to_json();
    
    // Verify JSON structure
    let parsed: serde_json::Value = serde_json::from_str(&json).unwrap();
    assert_eq!(parsed["code"], 500);
    assert_eq!(parsed["message"], "Test error message");
}

#[derive(MsgDef, Debug, Serialize, Deserialize)]
struct EchoRequest {
    message: String,
}

#[derive(MsgDef, Debug, Serialize, Deserialize)]
struct EchoResponse {
    message: String,
}

#[msg_flow(pattern = "test_echo")]
impl EchoRequest {
    #[message(pattern = "1")]
    async fn handle(&self) -> Result<EchoResponse> {
        Ok(EchoResponse {
            message: format!("echo: {}", self.message),
        })
    }
}

#[tokio::test]
async fn test_send_and_receive_message_over_nats() {
    // ----- server side: register handlers -----
    let server_client = ConnectOptions::new()
        .connect("localhost:4222")
        .await
        .expect("connect NATS as server");

    let ctx = Context::new(server_client);
    let ctx = Arc::new(ctx);

    // This calls the code generated by `#[msg_flow]` and spawns the NATS subscribers
    let regs: &[message_flow::RegisterFn] = registers!(EchoRequest);
    for reg in regs {
        reg(ctx.clone()).await.expect("register handler");
    }

    // Give NATS a moment to create the subscription
    tokio::time::sleep(std::time::Duration::from_millis(100)).await;

    // ----- client side: send request and wait for reply -----
    let client = async_nats::connect("localhost:4222")
        .await
        .expect("connect NATS as client");

    let request = EchoRequest {
        message: "hello".into(),
    };
    let payload = serde_json::to_vec(&request).expect("serialize request");

    // Subject is `base_pattern + '.' + message_pattern` → "test_echo.1"
    let msg = client
        .request("test_echo.1", payload.into())
        .await
        .expect("send request / receive reply");

    let response: EchoResponse =
        serde_json::from_slice(msg.payload.as_ref()).expect("deserialize response");

    assert_eq!(response.message, "echo: hello");
}


